export const PASSPORT_RU_SLUGS: string[] = Object.keys(RU);

/** The Russian copy plus the underlying sourced size, or null when there is no
    Russian page for that country — the route treats null as notFound(). */
export function getPassportRu(slug: string): { ru: PassportRuCopy; size: PassportSize } | null {
  const ru = RU[slug];
  const size = getPassportSize(slug);
  return ru && size ? { ru, size } : null;
}
