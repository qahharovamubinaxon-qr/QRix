/* Generates lib/home-i18n/ — one module per language — from a single source object.
 *
 * Why this exists: lib/home-i18n.ts was ONE 56.2 KB registry holding twelve
 * languages (zh hi es ar fr pt id de ja tr ur bn). Three CLIENT components each
 * read one slice of it, so every visitor downloaded all twelve. None of those
 * twelve is en, ru or uz — the three languages this site actually serves, which
 * are authored inline in the components. The audience downloaded 44.4 KB of JSON
 * it could not read. (M160; same shape as M159's barcode registry.)
 *
 * The split is generated rather than hand-typed because the input is 44 KB of
 * non-Latin copy in scripts nobody here proofreads — a transcription slip would
 * be invisible. scripts/test-home-i18n.mjs asserts the output is byte-identical
 * to the input, key for key.
 *
 * Re-run only if the source object below changes:
 *   node scripts/gen-home-i18n-split.mjs
 */

import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib", "home-i18n");

/* The source of truth is whichever exists: the pre-split single file (only on the
 * very first run) or the language modules themselves, re-read from disk. There is
 * deliberately no aggregate module to read instead — see readAll()'s note. */
async function loadSource() {
  const legacy = join(ROOT, "lib", "home-i18n.ts");
  const legacyFaq = join(ROOT, "lib", "home-faq-i18n.ts");
  if (existsSync(legacy)) {
    const { HOME_I18N } = await import(`file://${legacy.replace(/\\/g, "/")}`);
    const { FAQ_I18N } = await import(`file://${legacyFaq.replace(/\\/g, "/")}`);
    /* The two registries were separate modules holding the same twelve
     * languages, so a single visitor paid for both to read one language of
     * each. They merge here: one language = one file = one request. */
    const merged = {};
    for (const [code, v] of Object.entries(HOME_I18N)) {
      if (!FAQ_I18N[code]) throw new Error(`${code}: in HOME_I18N but has no FAQ_I18N entry`);
      merged[code] = { ...v, faq: FAQ_I18N[code] };
    }
    for (const code of Object.keys(FAQ_I18N)) {
      if (!merged[code]) throw new Error(`${code}: in FAQ_I18N but has no HOME_I18N entry`);
    }
    return merged;
  }
  const { readAll } = await import("./home-i18n-aggregate.mjs");
  return readAll();
}

const HOME_I18N = await loadSource();
const codes = Object.keys(HOME_I18N).sort();

mkdirSync(OUT, { recursive: true });

const BANNER = (extra) =>
  `// GENERATED by scripts/gen-home-i18n-split.mjs — do not edit by hand.\n${extra}`;

/* ---- the shared type ----------------------------------------------------- */
writeFileSync(
  join(OUT, "types.ts"),
  BANNER(`// Type only: erased before any bundler sees it, so importing this costs nothing.
`) +
    `
export type HomeUi = {
  pageT: Record<string, string>;
  homeFaq: { t: string; s: string };
  newsletter: { t: string; s: string; ph: string; btn: string; ok: string; err: string };
  /* The eight homepage FAQ Q&A. Merged in from what used to be a SECOND
   * twelve-language registry (lib/home-faq-i18n.ts) that the same client
   * component imported alongside this one — so one language now costs one
   * request instead of two whole registries. */
  faq: { q: string; a: string }[];
  /* Read by NO client component. It is the source npm run test:nav diffs
   * lib/nav-i18n.ts against, in both directions — the only thing standing
   * between the site header and silent translation drift. Do not drop it. */
  nav: Record<string, string>;
};
`,
  "utf8",
);

/* ---- one module per language --------------------------------------------- */
for (const code of codes) {
  writeFileSync(
    join(OUT, `${code}.ts`),
    BANNER(`// Homepage UI copy — ${code}. Reached only through loadHomeUi("${code}").\n`) +
      `import type { HomeUi } from "./types";

const ui: HomeUi = ${JSON.stringify(HOME_I18N[code], null, 2)};

export default ui;
`,
    "utf8",
  );
}

/* ---- the loader the client uses ------------------------------------------ */
const cases = codes
  .map((c) => `    case "${c}": return (await import("./${c}")).default;`)
  .join("\n");

writeFileSync(
  join(OUT, "index.ts"),
  BANNER(`// The ONLY entry point client code may use.
//
// en/ru/uz are authored inline in the components that render them, so they
// resolve to null WITHOUT a network round trip — that is the whole point, and
// it is why the common case now downloads nothing at all. Every other language
// costs one import of its own file (2.8-5.7 KB), never all twelve.
//
// Deferring is safe here in a way it usually is not: \`lang\` is useState("en")
// hydrated from localStorage in an effect, so every non-English visitor already
// renders English first. This extends a flash that exists today rather than
// introducing one, and a crawler still sees English either way.
`) +
    `import type { HomeUi } from "./types";

export type { HomeUi } from "./types";

/* The languages that live in this directory. en/ru/uz are deliberately absent. */
export const EXTRA_LANGS = ${JSON.stringify(codes)} as const;

export function hasHomeUi(lang: string): boolean {
  return (EXTRA_LANGS as readonly string[]).includes(lang);
}

/* A literal switch, not import(\`./\${lang}\`): a template import makes the
 * bundler emit every match as a candidate chunk and hides typos until runtime.
 * Returns null for a language served from inline copy. */
export async function loadHomeUi(lang: string): Promise<HomeUi | null> {
  switch (lang) {
${cases}
    default: return null;
  }
}
`,
  "utf8",
);

/* There is NO all.ts, and its absence is the design.
 *
 * An aggregate module that re-exports all twelve is one stray import away from
 * putting the whole registry back in the bundle — the exact defect M160 removed,
 * and a guard asserting "no client imports it" would be the only thing stopping
 * it. Node-side tools that genuinely need every language read the directory
 * instead (scripts/home-i18n-aggregate.mjs), which nothing a browser loads can
 * reach. The boundary is structural, not asserted. */

const total = codes.reduce(
  (n, c) => n + Buffer.byteLength(readFileSync(join(OUT, `${c}.ts`), "utf8"), "utf8"),
  0,
);
console.log(`wrote ${codes.length} language modules + types.ts + index.ts -> lib/home-i18n/`);
console.log(`  ${codes.join(" ")}`);
console.log(`  ${(total / 1024).toFixed(1)} KB of copy, none of it eager`);
