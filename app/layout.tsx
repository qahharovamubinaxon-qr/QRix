/* The families keep their REAL names — the canvas tools (promo film, AI
   generators, QR studio, poster maker) set ctx.font = "…px Unbounded /
   Space Mono / Inter", which a next/font hashed family name would break. So
   rather than next/font they are self-hosted as plain @font-face rules in
   app/fonts.css, generated by scripts/fetch-fonts.mjs.

   They used to come from fonts.googleapis.com via <link rel="stylesheet">.
   That put two third-party origins in front of first paint: the font file was
   not discoverable until our own CSS had loaded and the Google stylesheet had
   parsed, which measured 2637 ms for the LCP font on the homepage and 615 ms
   on a tool page — and the LCP element is a paragraph of text on every
   template. Same-origin plus the preload below, it starts at t=0 instead.

   Bricolage Grotesque has no cyrillic subset, so RU/UZ body text falls through
   to Inter; both are self-hosted with Google's own unicode-range blocks intact
   so each visitor still downloads only the subsets their page renders. */
const LCP_FONT = "/fonts/bricolage-grotesque-normal-300-latin.woff2";

